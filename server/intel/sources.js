// URL, coverage, access method, licence notes and refresh frequency. Static
// definitions live here; runtime state (connection status, last run, errors)
// is stored in the `sources` collection and merged in by sourceService.
//
// Rule: nothing in this file claims an API exists unless it has been
// confirmed. Where a jurisdiction only offers a web portal, the access method
// says so and the connector type is `csv` (permitted manual export/import).

export const REFRESH = {
  weekly: { label: 'Weekly', minPollHours: 24, note: 'The publisher updates this dataset about once a week, so checking more than once a day cannot surface anything new.' },
  daily: { label: 'Daily', minPollHours: 6, note: 'The publisher refreshes about once a day.' },
  manual: { label: 'Manual export', minPollHours: null, note: 'Records only change when you upload a new export from the portal.' },
  unknown: { label: 'Not published', minPollHours: 24, note: 'The publisher does not state a refresh schedule.' },
};

export const POLL_OPTIONS = [
  { id: 'manual', label: 'Manual refresh only', hours: null },
  { id: '6h', label: 'Every 6 hours', hours: 6 },
  { id: '12h', label: 'Every 12 hours', hours: 12 },
  { id: 'daily', label: 'Daily', hours: 24 },
];

/** Which poll options a source may offer, given its published refresh rate. */
export function allowedPollOptions(source) {
  const min = REFRESH[source.refreshFrequency]?.minPollHours;
  return POLL_OPTIONS.filter((o) => o.hours === null || min === null || min === undefined || o.hours >= min);
}

